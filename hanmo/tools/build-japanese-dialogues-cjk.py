#!/usr/bin/env python3
"""Append only dialogue UI CJK glyphs; preserve all old pixels/metrics.

Run with a Python containing fontTools/freetype. Old generated faces are the
input baseline: no full charset regeneration and no kana/reader face changes.
The output manifest records old-codepoint digests for reproducible verification.
"""
from pathlib import Path
import argparse, hashlib, json, re, subprocess, sys
ROOT = Path(__file__).resolve().parents[1]
SIZES = (8, 10, 12, 14, 16, 18)
FONT = ROOT / 'lib/EpdFont/builtinFonts'


def decode(path, shared=None):
    text = path.read_text()
    name = path.stem
    bitmap = re.search(rf'{name}Bitmaps\[\d+\] = \{{(.*?)\n\}};', text, re.S)
    glyph = re.search(rf'{name}Glyphs\[\] = \{{(.*?)\n\}};', text, re.S)
    interval = re.search(rf'{name}Intervals\[\] = \{{(.*?)\n\}};', text, re.S)
    tail = re.search(rf'static const EpdFontData {name} = \{{(.*?)\n\}};', text, re.S)
    assert bitmap and glyph and tail, path
    bits = bytes(int(x, 16) for x in re.findall(r'0x([\dA-Fa-f]+)', bitmap[1]))
    gs = [tuple(map(int, row)) for row in re.findall(r'\{\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*\}', glyph[1])]
    itext = interval[1] if interval else shared.read_text()
    intervals = [tuple(int(x, 16) for x in row) for row in re.findall(r'\{\s*(0x[\dA-Fa-f]+)\s*,\s*(0x[\dA-Fa-f]+)\s*,\s*(0x[\dA-Fa-f]+)\s*\}', itext)]
    mapping = {cp: gs[start + cp - a] for a, b, start in intervals for cp in range(a, b + 1)}
    assert len(mapping) == len(gs), path
    for g in gs: assert g[6] + g[5] <= len(bits)
    return bits, mapping, tail[1]


def digest(bits, glyphs, cps):
    h = hashlib.sha256()
    for cp in sorted(cps):
        g = glyphs[cp]
        h.update(json.dumps([cp, *g[:6]], separators=(',', ':')).encode())
        h.update(bits[g[6]:g[6] + g[5]])
    return h.hexdigest()


def encode(name, bits, glyphs, tail):
    cps = sorted(glyphs)
    intervals = []
    for i, cp in enumerate(cps):
        if intervals and cp == intervals[-1][1] + 1:
            intervals[-1][1] = cp
        else:
            intervals.append([cp, cp, i])
    fields = [x.strip() for x in tail.strip().rstrip(',').split(',')]
    fields[2] = name + 'Intervals'
    fields[3] = str(len(intervals))
    output = '// Generated by tools/build-japanese-dialogues-cjk.py; old glyphs preserved.\n#pragma once\n#include "EpdFontData.h"\n\n'
    output += f'static const uint8_t {name}Bitmaps[{len(bits)}] = {{\n'
    output += ''.join('    ' + ', '.join(f'0x{x:02X}' for x in bits[i:i + 16]) + ',\n' for i in range(0, len(bits), 16)) + '};\n\n'
    output += f'static const EpdGlyph {name}Glyphs[] = {{\n'
    output += ''.join('    { ' + ', '.join(map(str, glyphs[cp])) + ' }, // U+' + f'{cp:04X}\n' for cp in cps) + '};\n\n'
    output += f'static const EpdUnicodeInterval {name}Intervals[] = {{\n'
    output += ''.join(f'    {{ 0x{a:X}, 0x{b:X}, 0x{i:X} }},\n' for a, b, i in intervals) + '};\n\n'
    output += f'static const EpdFontData {name} = {{\n' + ''.join('    ' + x + ',\n' for x in fields) + '};\n'
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    shared = FONT / 'notosans_cjk_common_intervals.h'
    manifest = ROOT / 'tools/japanese-dialogues-cjk-baseline.json'
    labels = []
    for locale in ('chinese', 'chinese-traditional'):
        for line in (ROOT / 'lib/I18n/translations' / (locale + '.yaml')).read_text().splitlines():
            if line.startswith(('STR_JP_DIALOGUES_', 'STR_CHANGE_JP_DIALOGUES_', 'STR_JP_SENTENCES_INFO:')):
                labels.append(json.loads(line.split(': ', 1)[1]))
    needed = {ord(c) for s in labels for c in s if '\u4e00' <= c <= '\u9fff'}
    if args.verify:
        records = json.loads(manifest.read_text())
        for size in SIZES:
            bits, mapping, _ = decode(FONT / f'notosans_cjk_{size}.h', shared)
            r = records[str(size)]
            assert digest(bits, mapping, r['oldCodepoints']) == r['oldPixelsMetricsSha256'], size
            assert needed <= mapping.keys(), size
        print('CJK coverage and all pre-existing glyph pixels/metrics preserved: 6/6')
        return
    assert not manifest.exists(), 'Do not rebuild a completed glyph expansion'
    temp = ROOT / 'build/japanese-dialogues-cjk'
    temp.mkdir(parents=True, exist_ok=True)
    records, outputs = {}, []
    for size in SIZES:
        name = f'notosans_cjk_{size}'
        bits, mapping, tail = decode(FONT / (name + '.h'), shared)
        oldcps = sorted(mapping)
        oldsha = digest(bits, mapping, oldcps)
        missing = sorted(needed - mapping.keys())
        if missing:
            part = temp / (name + '.h')
            with part.open('w') as out:
                subprocess.run([sys.executable, str(ROOT / 'lib/EpdFont/scripts/fontconvert.py'), name, str(size), str(FONT / 'source/NotoSansSC/NotoSansSC-Regular.otf'), '--2bit', '--characters', ''.join(map(chr, missing))], stdout=out, check=True)
            newbits, newglyphs, _ = decode(part)
            assert set(missing) <= newglyphs.keys(), size
            oldlength = len(bits)
            for cp in missing:
                g = list(newglyphs[cp]); g[6] += oldlength; mapping[cp] = tuple(g)
            bits += newbits
        assert digest(bits, mapping, oldcps) == oldsha
        output = temp / (name + '.complete.h')
        output.write_text(encode(name, bits, mapping, tail))
        # Decoder expects the variable name matching basename.
        check = temp / (name + '.h'); check.write_bytes(output.read_bytes())
        rb, rm, _ = decode(check)
        assert digest(rb, rm, oldcps) == oldsha and needed <= rm.keys()
        outputs.append((FONT / (name + '.h'), output))
        records[str(size)] = {'oldCodepoints': oldcps, 'oldPixelsMetricsSha256': oldsha, 'added': [chr(cp) for cp in missing]}
    for target, output in outputs: target.write_bytes(output.read_bytes())
    subprocess.run([sys.executable, str(ROOT / 'lib/EpdFont/scripts/share-cn-font-intervals.py'), str(FONT)], check=True)
    manifest.write_text(json.dumps(records, indent=2, ensure_ascii=False) + '\n')
    subprocess.run([sys.executable, str(Path(__file__)), '--verify'], check=True)
    print(json.dumps({k: v['added'] for k, v in records.items()}, ensure_ascii=False))

if __name__ == '__main__': main()
