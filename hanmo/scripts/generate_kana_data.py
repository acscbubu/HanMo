from pathlib import Path
import json
r=Path(__file__).resolve().parents[1];d=json.loads((r/'data/japanese/kana-basic.json').read_text())
q=lambda v:json.dumps(v,ensure_ascii=False)
out=['// Generated by scripts/generate_kana_data.py from authored lesson data.','#pragma once','#include <array>','namespace kana {','struct Card { const char *hiragana,*katakana,*romaji,*example,*meaning,*exampleRomaji,*soundHint; };','inline constexpr std::array<Card,46> cards = {{']
out += ['  {'+','.join(q(v) for v in row)+'},' for row in d['cards']]
out += ['}};','struct Group { const char* label; int start,count; };','inline constexpr std::array<Group,11> groups = {{']
out += ['  {'+q(label)+','+str(start)+','+str(count)+'},' for label,start,count in d['groups']]
out += ['}};','}  // namespace kana','']
(r/'src/activities/apps/japanese/KanaData.generated.h').write_text('\n'.join(out))
