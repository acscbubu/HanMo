#!/usr/bin/env python3
"""Validate edition-1 authored data and emit a deterministic UTF-8 C++ lesson."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
REFERENCES = [
    'https://www.irodori.jpf.go.jp/assets/data/starter/pdf/X_L03.pdf',
    'https://www.irodori.jpf.go.jp/assets/data/starter/pdf/X_L05.pdf',
]


def string(value, field, maximum=160):
    if not isinstance(value, str) or not value.strip() or len(value) > maximum:
        raise ValueError(f'{field}: expected a nonempty bounded string')
    if any(ord(c) < 32 or 0xD800 <= ord(c) <= 0xDFFF for c in value):
        raise ValueError(f'{field}: invalid UTF-8 or control character')


def validate(data):
    if not isinstance(data, dict) or type(data.get('edition')) is not int or data['edition'] != 1:
        raise ValueError('Expected edition 1')
    provenance = data.get('provenance')
    if not isinstance(provenance, dict) or provenance.get('authoredForHanMo') is not True or provenance.get('isOriginalJpfText') is not False:
        raise ValueError('Explicit HanMo authorship / not original JPF text required')
    string(provenance.get('claim'), 'provenance.claim', 512)
    if 'not' not in provenance['claim'].lower() or provenance.get('referenceUrls') != REFERENCES:
        raise ValueError('Reference-only provenance required')
    cards = data.get('cards')
    if not isinstance(cards, list) or len(cards) != 6:
        raise ValueError('Exactly six cards required')
    seen = set()
    for index, card in enumerate(cards):
        if not isinstance(card, dict):
            raise ValueError('Each card must be an object')
        for field in ('id', 'japanese', 'kanaReading', 'romaji', 'meaning'):
            string(card.get(field), field)
        if card['id'] in seen or card['id'] != f'sentence-{index + 1:02d}':
            raise ValueError('Stable unique ordered sentence IDs required')
        seen.add(card['id'])
        for field in ('japanese', 'kanaReading'):
            if not re.fullmatch(r'[\u3041-\u3096]+。', card[field]):
                raise ValueError(f'{field}: first lesson must be hiragana with final 。')
        if card['kanaReading'] != card['japanese']:
            raise ValueError('First-lesson kanaReading must match authored hiragana')
        if not re.fullmatch(r'[a-z]+(?: [a-z]+)+\.', card['romaji']):
            raise ValueError('romaji: lower-case words, single spaces, final period required')
        if index < 3 and ' wa ' not in card['romaji']:
            raise ValueError('Topic は is read wa')
        if index >= 3 and ' o ' not in card['romaji']:
            raise ValueError('Object を is read o')
        notes = card.get('grammarNotes')
        if not isinstance(notes, list) or len(notes) != 2:
            raise ValueError('Exactly two separate grammar notes required')
        for note in notes:
            string(note, 'grammarNotes', 28)
        vocabulary = card.get('vocabularyCardId')
        if type(vocabulary) is not int or vocabulary < -1 or vocabulary > 45 or vocabulary == 44:
            raise ValueError('Vocabulary must reference a word card (never short-phrase card 44) or -1')
        if vocabulary != [45, 5, 16, -1, 12, 45][index]:
            raise ValueError('First lesson vocabulary references do not match the reviewed nouns')


def generate(data):
    validate(data)
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines = [
        '// Generated by scripts/generate_japanese_sentences.py; do not edit.',
        '// Original HanMo lesson text; JPF references inform grammar only.',
        '#pragma once', '#include <array>',
        'namespace japanese::sentences {',
        'struct Card {',
        '  const char *id, *japanese, *kanaReading, *romaji, *meaning;',
        '  std::array<const char*, 2> grammarNotes;',
        '  int vocabularyCardId;', '};',
        'inline constexpr int kCardCount = 6;',
        'inline constexpr std::array<Card, kCardCount> cards = {{',
    ]
    for card in data['cards']:
        fields = ', '.join(quote(card[field]) for field in ('id', 'japanese', 'kanaReading', 'romaji', 'meaning'))
        notes = ', '.join(quote(note) for note in card['grammarNotes'])
        lines.append('  {' + fields + ', {{' + notes + '}}, ' + str(card['vocabularyCardId']) + '},')
    lines += ['}};', '}  // namespace japanese::sentences', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / 'data/japanese/sentences-basic.json')
    parser.add_argument('--output', type=Path, default=ROOT / 'src/activities/apps/japanese/JapaneseSentences.generated.h')
    parser.add_argument('--check', action='store_true', help='Fail if stale; do not write')
    args = parser.parse_args()
    try:
        output = generate(json.loads(args.source.read_text(encoding='utf-8'))).encode('utf-8')
    except (ValueError, OSError) as error:
        parser.error(str(error))
    if args.check:
        if not args.output.is_file() or args.output.read_bytes() != output:
            parser.exit(1, 'Sentence header is missing or stale\n')
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(output)
    print('Checked six authored sentence cards' if args.check else 'Generated six authored sentence cards')


if __name__ == '__main__':
    main()
